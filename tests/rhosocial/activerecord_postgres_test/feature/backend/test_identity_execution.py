class TestIdentityProbeDeclaration:
    """The probes answer the measured boundary and the renderer agrees."""

    @pytest.mark.parametrize(
        "version,expected",
        [((9, 6, 0), False), ((10, 0, 0), True), ((14, 0, 0), True), ((18, 0, 0), True)],
        ids=["pg9", "pg10", "pg14", "pg18"],
    )
    def test_mechanism_probe_carries_the_version_boundary(self, version, expected):
        dialect = PostgresDialect(version=version)
        assert dialect.supports_identity_column() is expected

    @pytest.mark.parametrize(
        "version", [(10, 0, 0), (14, 0, 0), (18, 0, 0)], ids=["pg10", "pg14", "pg18"]
    )
    def test_every_option_probe_is_declared(self, version):
        dialect = PostgresDialect(version=version)
        for probe in (
            "supports_identity_generation_always",
            "supports_identity_start",
            "supports_identity_increment",
            "supports_identity_minvalue",
            "supports_identity_maxvalue",
            "supports_identity_cycle",
            "supports_identity_cache",
        ):
            assert getattr(dialect, probe)() is True, probe

    def test_cache_is_declared_and_no_cache_is_refused(self):
        """CACHE n is expressible; NO CACHE has no identity spelling.

        The positive spelling is accepted by the server (measured:
        ``GENERATED BY DEFAULT AS IDENTITY (CACHE 1)``), while ``NO CACHE`` is
        a syntax error there, so the negative is refused by name instead of
        being rendered or dropped.
        """
        dialect = PostgresDialect(version=(18, 0, 0))
        assert dialect.supports_identity_cache() is True
        sql, _ = dialect.format_identity_clause(IdentityClause(dialect, cache=10))
        assert "CACHE 10" in sql
        with pytest.raises(UnsupportedFeatureError, match="IDENTITY NO CACHE"):
            dialect.format_identity_clause(IdentityClause(dialect, no_cache=True))

    def test_pg9_refuses_the_clause(self):
        """PostgreSQL 9 has no identity columns, so the formatter refuses.

        The refusal is the point: there is no fallback to SERIAL (the explicit
        SERIAL type path is covered separately and executes on every version).
        """
        dialect = PostgresDialect(version=(9, 6, 0))
        with pytest.raises(UnsupportedFeatureError, match="IDENTITY column"):
            dialect.format_identity_clause(IdentityClause(dialect))

    def test_auto_increment_marker_is_declared_false_and_refused(self):
        dialect = PostgresDialect(version=(18, 0, 0))
        assert dialect.supports_auto_increment_column() is False
        with pytest.raises(UnsupportedFeatureError, match="AUTO_INCREMENT column"):
            AutoIncrementClause(dialect).to_sql()


