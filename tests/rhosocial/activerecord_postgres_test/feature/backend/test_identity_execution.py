def _identity_table(dialect, table_name, **identity_kwargs):
    return CreateTableExpression(
        dialect=dialect,
        table=Table(dialect, table_name),
        columns=[
            ColumnDefinition(
                dialect,
                "id",
                IntegerType(dialect=dialect),
                attributes=[IdentityAttribute(**identity_kwargs)],
            )
        ],
    )


def _auto_increment_table(dialect, table_name):
    return CreateTableExpression(
        dialect=dialect,
        table=Table(dialect, table_name),
        columns=[
            ColumnDefinition(
                dialect,
                "id",
                IntegerType(dialect=dialect),
                constraints=[
                    ColumnConstraint(
                        dialect,
                        ColumnConstraintType.PRIMARY_KEY,
                        is_auto_increment=True,
                    )
                ],
            )
        ],
    )


def _serial_table(dialect, table_name, data_type):
    return CreateTableExpression(
        dialect=dialect,
        table=Table(dialect, table_name),
        columns=[ColumnDefinition(dialect, "id", data_type(dialect=dialect))],
    )


def _confirm(backend, expression, table_name):
    dialect = backend.dialect
    return confirm_expression_execution(
        backend,
        expression,
        teardown=[
            DropTableExpression(dialect, Table(dialect, table_name), if_exists=True)
        ],
    )


class TestIdentityExecutionConfirmation:
    """Acceptance is confirmed against the live server, per version."""

    def test_sentinel_rejected_and_control_accepted(self, postgres_backend):
        """The classifier must see both answers before any verdict is trusted."""
        assert (
            classify_execution(postgres_backend, "THIS IS NOT SQL")
            is ExecutionOutcome.REJECTED
        )
        assert (
            classify_execution(postgres_backend, "SELECT 1")
            is ExecutionOutcome.ACCEPTED
        )

    def test_bare_identity_matches_the_declaration(self, postgres_backend):
        dialect = postgres_backend.dialect
        outcome = _confirm(
            postgres_backend,
            _identity_table(dialect, "test_identity_exec_bare"),
            "test_identity_exec_bare",
        )
        if dialect.supports_identity_column():
            assert outcome is ExecutionOutcome.ACCEPTED
        else:
            assert outcome is ExecutionOutcome.NOT_RENDERED

    def test_always_with_options_matches_the_declaration(self, postgres_backend):
        dialect = postgres_backend.dialect
        outcome = _confirm(
            postgres_backend,
            _identity_table(
                dialect,
                "test_identity_exec_options",
                generation="ALWAYS",
                start=100,
                increment=5,
                minvalue=1,
                maxvalue=1000000,
                cycle=True,
            ),
            "test_identity_exec_options",
        )
        if dialect.supports_identity_column():
            assert outcome is ExecutionOutcome.ACCEPTED
        else:
            assert outcome is ExecutionOutcome.NOT_RENDERED

    def test_no_cycle_is_executable(self, postgres_backend):
        dialect = postgres_backend.dialect
        outcome = _confirm(
            postgres_backend,
            _identity_table(
                dialect, "test_identity_exec_nocycle", cycle=False
            ),
            "test_identity_exec_nocycle",
        )
        if dialect.supports_identity_column():
            assert outcome is ExecutionOutcome.ACCEPTED
        else:
            assert outcome is ExecutionOutcome.NOT_RENDERED

    def test_auto_increment_constraint_matches_the_declaration(self, postgres_backend):
        """The legacy is_auto_increment flag routes through the identity gate."""
        dialect = postgres_backend.dialect
        outcome = _confirm(
            postgres_backend,
            _auto_increment_table(dialect, "test_identity_exec_legacy"),
            "test_identity_exec_legacy",
        )
        if dialect.supports_identity_column():
            assert outcome is ExecutionOutcome.ACCEPTED
        else:
            assert outcome is ExecutionOutcome.NOT_RENDERED


class TestSerialTypeExecution:
    """SERIAL is a type, not an identity clause: it executes on every version."""

    @pytest.mark.parametrize(
        "data_type,table_suffix",
        [
            (PostgresSmallSerialType, "smallserial"),
            (PostgresSerialType, "serial"),
            (PostgresBigSerialType, "bigserial"),
        ],
        ids=["smallserial", "serial", "bigserial"],
    )
    def test_serial_type_executes(self, postgres_backend, data_type, table_suffix):
        dialect = postgres_backend.dialect
        table_name = f"test_identity_exec_{table_suffix}"
        outcome = _confirm(
            postgres_backend,
            _serial_table(dialect, table_name, data_type),
            table_name,
        )
        assert outcome is ExecutionOutcome.ACCEPTED
