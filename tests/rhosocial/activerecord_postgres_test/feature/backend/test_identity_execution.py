# tests/rhosocial/activerecord_postgres_test/feature/backend/test_identity_execution.py
"""Execution confirmation for PostgreSQL identity / auto-increment / SERIAL DDL.

Rendering is not execution. PostgreSQL 9 renders a well-formed
``GENERATED ... AS IDENTITY`` clause and its server rejects it with
``syntax error at or near "GENERATED"``, which is exactly the failure this
file exists to catch. Every clause is built with the expression layer, rendered
by the dialect the live backend carries, and executed against that server.

The three outcomes stay distinct, as core's helper requires:

* the server accepts -> ``ACCEPTED``;
* the server rejects SQL the expression rendered -> the helper raises, and
  that is a defect;
* the expression refuses to render (``UnsupportedFeatureError``) ->
  ``NOT_RENDERED``, which on PostgreSQL 9 is the *correct* answer for an
  identity column, not a skip.

Each verdict is preceded by a sentinel: a deliberately invalid statement must
be classified ``REJECTED``, or a null result could be read as acceptance.
"""

import pytest

from rhosocial.activerecord.base import IdentityAttribute
from rhosocial.activerecord.backend.dialect.exceptions import UnsupportedFeatureError
from rhosocial.activerecord.backend.expression.execution_testing import (
    ExecutionOutcome,
    classify_execution,
    confirm_expression_execution,
)
from rhosocial.activerecord.backend.expression.objects import Table
from rhosocial.activerecord.backend.expression.statements import (
    AutoIncrementClause,
    ColumnConstraint,
    ColumnConstraintType,
    ColumnDefinition,
    CreateTableExpression,
    DropTableExpression,
    IdentityClause,
)
from rhosocial.activerecord.backend.expression.types import IntegerType
from rhosocial.activerecord.backend.impl.postgres.dialect import PostgresDialect
from rhosocial.activerecord.backend.impl.postgres.expression.types import (
    PostgresBigSerialType,
    PostgresSerialType,
    PostgresSmallSerialType,
)


